#!/usr/bin/env python3
"""Install generated CAD agents and skills for supported coding harnesses."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import sys
from typing import NamedTuple

ROOT = Path(__file__).resolve().parents[1]
SKILLS = ROOT / "skills"
GENERATED = ROOT / "harness"
HARNESS_NAMES = ("claude", "codex", "opencode", "kiro")
MARKER = "<!-- Generated by cad-agent; do not edit. -->"
STATE_NAME = ".cad-agent-install.json"


class FilePair(NamedTuple):
    source: Path
    target: Path
    key: str


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 128), b""):
            digest.update(block)
    return digest.hexdigest()


def skill_files() -> list[Path]:
    files: list[Path] = []
    for skill in sorted(SKILLS.glob("cad-*")):
        if not skill.is_dir():
            continue
        for current, dirs, names in os.walk(skill, followlinks=False):
            dirs[:] = sorted(name for name in dirs if name not in {"tests", "__pycache__"})
            for name in sorted(names):
                path = Path(current) / name
                if path.suffix != ".pyc" and not path.is_symlink():
                    files.append(path)
    return files


def harness_layout(harness: str, project: Path, home: Path | None) -> tuple[Path, Path, Path | None]:
    """Return skills directory, agent directory, and optional command directory."""
    if harness == "claude":
        scope = home / ".claude" if home is not None else project / ".claude"
        return scope / "skills", scope / "agents", None
    if harness == "codex":
        if home is not None:
            return home / ".agents/skills", home / ".codex/agents", None
        return project / ".agents/skills", project / ".codex/agents", None
    if harness == "opencode":
        scope = home / ".config/opencode" if home is not None else project / ".opencode"
        return scope / "skills", scope / "agents", scope / "commands"
    if harness == "kiro":
        scope = home / ".kiro" if home is not None else project / ".kiro"
        return scope / "skills", scope / "agents", None
    raise ValueError(f"unknown harness {harness!r}")


def relative_key(target: Path, root: Path) -> str:
    try:
        key = target.relative_to(root).as_posix()
    except ValueError as error:
        raise ValueError(f"install destination escaped scope: {target}") from error
    if key.startswith("../") or key == "..":
        raise ValueError(f"install destination escaped scope: {target}")
    return key


def file_pairs(harnesses: tuple[str, ...], scope: Path, home: Path | None = None) -> list[FilePair]:
    pairs: list[FilePair] = []
    project = scope if home is None else home
    for harness in harnesses:
        skills_dir, agents_dir, commands_dir = harness_layout(harness, project, home)
        for source in skill_files():
            target = skills_dir / source.relative_to(SKILLS)
            pairs.append(FilePair(source, target, relative_key(target, scope)))
        agent_root = GENERATED / harness / "agents"
        for source in sorted(agent_root.iterdir()):
            if source.is_file():
                target = agents_dir / source.name
                pairs.append(FilePair(source, target, relative_key(target, scope)))
        if commands_dir is not None:
            source = GENERATED / "opencode/commands/cad-flow.md"
            target = commands_dir / source.name
            pairs.append(FilePair(source, target, relative_key(target, scope)))
    return pairs


def load_state(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise ValueError(f"invalid installer ownership file {path}: {error}") from error
    if not isinstance(value, dict) or value.get("format") != 1 or not isinstance(value.get("files"), dict):
        raise ValueError(f"invalid installer ownership file {path}")
    files = value["files"]
    if any(not isinstance(key, str) or not isinstance(digest, str) for key, digest in files.items()):
        raise ValueError(f"invalid file entries in installer ownership file {path}")
    for key in files:
        relative = Path(key)
        if relative.is_absolute() or not relative.parts or ".." in relative.parts:
            raise ValueError(f"unsafe path in installer ownership file {path}: {key!r}")
    return files


def safe_destination(target: Path, scope: Path) -> None:
    relative_key(target, scope)
    parent = target.parent
    while parent != scope:
        if parent.exists() and parent.is_symlink():
            raise ValueError(f"refusing symlink destination directory {parent}")
        if parent.exists() and not parent.is_dir():
            raise ValueError(f"refusing non-directory destination parent {parent}")
        parent = parent.parent
    if target.is_symlink():
        raise ValueError(f"refusing symlink destination {target}")
    if target.exists() and not target.is_file():
        raise ValueError(f"refusing to overwrite non-file destination {target}")


def write_state(path: Path, owned: dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"format": 1, "files": dict(sorted(owned.items()))}, indent=2) + "\n", encoding="utf-8")


def generated_marker(path: Path) -> bool:
    try:
        if path.suffix == ".json":
            return MARKER in json.loads(path.read_text(encoding="utf-8")).get("prompt", "")
        return MARKER in path.read_text(encoding="utf-8")
    except (OSError, UnicodeError, json.JSONDecodeError, AttributeError):
        return False


def install(pairs: list[FilePair], scope: Path, dry_run: bool) -> int:
    state_path = scope / STATE_NAME
    safe_destination(state_path, scope)
    previous = load_state(state_path)
    planned: list[tuple[FilePair, bool, bool]] = []
    for pair in pairs:
        source, target = pair.source, pair.target
        safe_destination(target, scope)
        owned_hash = previous.get(pair.key)
        if not target.exists():
            planned.append((pair, True, True))
            continue
        target_hash = sha256(target)
        source_hash = sha256(source)
        if owned_hash is not None:
            if target_hash != owned_hash:
                raise ValueError(f"installed CAD file was modified; refusing to overwrite {target}")
        if owned_hash is not None:
            planned.append((pair, target_hash != source_hash, True))
            continue
        if target_hash == source_hash:
            planned.append((pair, False, True))
            continue
        if generated_marker(target):
            raise ValueError(f"generated CAD file differs from the current source; refusing to overwrite {target}")
        raise ValueError(f"refusing to overwrite non-cad file {target}")

    if dry_run:
        for pair, needs_write, _claim in planned:
            print(f"would {'install' if needs_write else 'keep'} {pair.target}")
        if any(claim for _pair, _write, claim in planned) and not state_path.exists():
            print(f"would record ownership {state_path}")
        return 0

    owned = dict(previous)
    wrote = False
    for pair, needs_write, claim in planned:
        if needs_write:
            pair.target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(pair.source, pair.target)
            print(f"installed {pair.target}")
            wrote = True
        if claim:
            owned[pair.key] = sha256(pair.target)
    if owned != previous:
        write_state(state_path, owned)
        if not previous:
            print(f"recorded {state_path}")
    elif not wrote:
        print("already installed; no files changed")
    return 0


def matching_prefixes(harnesses: tuple[str, ...]) -> tuple[str, ...]:
    prefixes: list[str] = []
    if "claude" in harnesses:
        prefixes.extend((".claude/skills/", ".claude/agents/"))
    if "codex" in harnesses:
        prefixes.extend((".agents/skills/", ".codex/agents/"))
    if "opencode" in harnesses:
        prefixes.extend((".opencode/skills/", ".opencode/agents/", ".opencode/commands/", ".config/opencode/skills/", ".config/opencode/agents/", ".config/opencode/commands/"))
    if "kiro" in harnesses:
        prefixes.extend((".kiro/skills/", ".kiro/agents/"))
    return tuple(prefixes)


def uninstall(scope: Path, harnesses: tuple[str, ...], dry_run: bool) -> int:
    state_path = scope / STATE_NAME
    safe_destination(state_path, scope)
    owned = load_state(state_path)
    prefixes = matching_prefixes(harnesses)
    selected = {key: digest for key, digest in owned.items() if key.startswith(prefixes)}
    for key, digest in selected.items():
        target = (scope / key).resolve()
        relative_key(target, scope)
        safe_destination(target, scope)
        if target.is_file() and sha256(target) != digest:
            raise ValueError(f"installed CAD file was modified; refusing to remove {target}")
    if dry_run:
        for key in sorted(selected):
            print(f"would uninstall {scope / key}")
        if selected:
            remaining = {key: value for key, value in owned.items() if key not in selected}
            print(f"would {'update' if remaining else 'remove'} ownership {state_path}")
        else:
            print("no installed CAD files found")
        return 0

    for key in sorted(selected, reverse=True):
        target = scope / key
        if target.is_file():
            target.unlink()
            print(f"uninstalled {target}")
        parent = target.parent
        while parent != scope:
            try:
                parent.rmdir()
            except OSError:
                break
            parent = parent.parent
    remaining = {key: value for key, value in owned.items() if key not in selected}
    if selected:
        if remaining:
            write_state(state_path, remaining)
        elif state_path.exists():
            state_path.unlink()
            print(f"removed {state_path}")
    else:
        print("no installed CAD files found")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--harness", choices=(*HARNESS_NAMES, "all"), required=True)
    scope_group = parser.add_mutually_exclusive_group()
    scope_group.add_argument("--user", action="store_true", help="install under the current user's harness directory")
    scope_group.add_argument("--project", type=Path, help="project directory (default: current directory)")
    parser.add_argument("--dry-run", action="store_true", help="show exact paths without changing files")
    parser.add_argument("--uninstall", action="store_true", help="remove files recorded as installed by this tool")
    args = parser.parse_args(argv)
    harnesses = HARNESS_NAMES if args.harness == "all" else (args.harness,)
    if not args.user and args.project is not None and not args.project.expanduser().resolve().is_dir():
        print(f"FAIL: project directory must exist: {args.project}", file=sys.stderr)
        return 1
    if not args.user and args.project is None and (Path.cwd().resolve() / "harness/install.py").is_file():
        print("FAIL: refusing to install into the cad-agent checkout implicitly; pass --project explicitly", file=sys.stderr)
        return 1
    home = Path(os.environ.get("HOME", str(Path.home()))).expanduser().resolve() if args.user else None
    scope = home if home is not None else (args.project or Path.cwd()).expanduser().resolve()
    try:
        if not scope.is_dir():
            raise ValueError(f"project/user install root must be an existing directory: {scope}")
        if args.uninstall:
            return uninstall(scope, harnesses, args.dry_run)
        return install(file_pairs(harnesses, scope, home), scope, args.dry_run)
    except (OSError, ValueError) as error:
        print(f"FAIL: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())