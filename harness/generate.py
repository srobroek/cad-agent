#!/usr/bin/env python3
"""Render neutral CAD agent sources as native harness agent profiles.

Canonical agent Markdown in agents/ uses name, description, capabilities, and
skills. Generated files are committed under harness/{claude,codex,opencode,kiro}/.
"""

from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from pathlib import Path
import re
import sys
import yaml

ROOT = Path(__file__).resolve().parents[1]
AGENTS = ROOT / "agents"
SKILLS = ROOT / "skills"
OUTPUTS = {harness: ROOT / "harness" / harness / "agents" for harness in ("claude", "codex", "opencode", "kiro")}
OPENCODE_COMMAND = ROOT / "harness" / "opencode" / "commands" / "cad-flow.md"
WORK_DIR, SHELL = ".cad-work", "uv *"
CAPABILITIES = {"read", "write-scratch", "shell-uv", "web"}
EXPECTED_AGENTS = {"cad-analyst", "cad-concept-designer", "cad-dfm-reviewer", "cad-mech-reviewer", "cad-part-designer", "cad-sourcing-researcher"}
OWNERSHIP_MARKER = "<!-- Generated by cad-agent; do not edit. -->"
CLAUDE_TOOLS = {
    "read": ("Read", "Grep", "Glob"), "write-scratch": ("Edit", "Write"),
    "shell-uv": ("Bash",), "web": ("WebSearch", "WebFetch"),
}


@dataclass(frozen=True)
class Agent:
    name: str
    description: str
    prompt: str
    capabilities: tuple[str, ...]
    skills: tuple[str, ...]

    @property
    def writes(self) -> bool:
        return "write-scratch" in self.capabilities

    @property
    def shell(self) -> bool:
        return "shell-uv" in self.capabilities

    @property
    def web(self) -> bool:
        return "web" in self.capabilities


def parse_agent(path: Path) -> Agent:
    text = path.read_text(encoding="utf-8")
    match = re.match(r"\A---\n(.*?)\n---\n(.*)\Z", text, re.DOTALL)
    if not match:
        raise ValueError(f"{path}: expected YAML frontmatter followed by a Markdown prompt")
    try:
        fields = yaml.safe_load(match.group(1))
    except yaml.YAMLError as error:
        raise ValueError(f"{path}: invalid YAML frontmatter: {error}") from error
    if not isinstance(fields, dict) or not all(isinstance(key, str) for key in fields):
        raise ValueError(f"{path}: frontmatter must be a YAML mapping")
    required = {"name", "description", "capabilities", "skills"}
    if fields.keys() != required:
        raise ValueError(f"{path}: expected only neutral fields; missing={sorted(required - fields.keys())}, unexpected={sorted(fields.keys() - required)}")
    name, description = fields["name"], fields["description"]
    if not isinstance(name, str) or not re.fullmatch(r"cad-[a-z0-9-]+", name) or name != path.stem:
        raise ValueError(f"{path}: name must be a cad-* kebab-case id matching the file name")
    if not isinstance(description, str) or not description:
        raise ValueError(f"{path}: description must be a non-empty string")
    if not isinstance(fields["capabilities"], list) or not isinstance(fields["skills"], list):
        raise ValueError(f"{path}: capabilities and skills must be YAML lists")
    if not all(isinstance(value, str) for value in (*fields["capabilities"], *fields["skills"])):
        raise ValueError(f"{path}: capabilities and skills entries must be strings")
    capabilities, skills = tuple(fields["capabilities"]), tuple(fields["skills"])
    if not capabilities or set(capabilities) - CAPABILITIES or len(set(capabilities)) != len(capabilities):
        raise ValueError(f"{path}: capabilities must be distinct names from {sorted(CAPABILITIES)}; got {capabilities!r}")
    if not skills or len(set(skills)) != len(skills):
        raise ValueError(f"{path}: skills must be a non-empty list of distinct CAD skills")
    missing = [skill for skill in skills if not (SKILLS / skill / "SKILL.md").is_file()]
    if missing:
        raise ValueError(f"{path}: skills name files CAD does not ship: {missing}")
    prompt = match.group(2).strip()
    if not prompt:
        raise ValueError(f"{path}: prompt must not be empty")
    forbidden = (r"skill://", r"xd://", r"\bautoloadSkills\b", r"\bBeads\b", r"\bOMP\b", r"@task\b", r"@reviewer\b", r"\.omp-plugin\b", r"\bPI_SESSION_ID\b")
    present = [term for term in forbidden if re.search(term, prompt, re.IGNORECASE)]
    if present:
        raise ValueError(f"{path}: prompt contains harness-coupled terms {present}")
    return Agent(name, description, prompt, capabilities, skills)


def agents() -> list[Agent]:
    sources = sorted(AGENTS.glob("*.md"))
    if {path.stem for path in sources} != EXPECTED_AGENTS:
        raise ValueError(f"agent sources must be exactly {sorted(EXPECTED_AGENTS)}")
    return [parse_agent(path) for path in sources]


def prompt_comment(agent: Agent, harness: str) -> str:
    lines = [OWNERSHIP_MARKER]
    if harness == "claude":
        gaps = []
        if agent.writes:
            gaps.append("Claude's native Edit and Write tools cannot be scoped to .cad-work by an agent file")
        if agent.shell:
            gaps.append("the Bash tool allowlist cannot restrict commands to uv")
        if gaps:
            lines.append("<!-- CAD policy: " + "; ".join(gaps) + "; follow the scratch-path and uv-only rules in this prompt. -->")
    if harness == "codex":
        lines.append("<!-- CAD policy: Codex custom agents have no general tool allowlist or .cad-work-only sandbox; capability limits are prompt policy, and the agent inherits its parent's access. -->")
        if agent.web:
            lines.append("<!-- CAD note: Codex custom agents inherit web access from the parent session; this format does not define a per-agent web tool toggle. -->")
    if harness == "opencode" and agent.shell:
        lines.append("<!-- CAD policy: OpenCode shell patterns are host-authority and best-effort; they cannot enforce the .cad-work write boundary for shell commands. -->")
    if harness == "kiro" and agent.writes and agent.shell:
        lines.append("<!-- CAD policy: Kiro's fs_write rules scope direct file tools, but uv shell commands still need the host command sandbox to enforce filesystem limits. Follow the .cad-work-only rule in this prompt. -->")
    return "\n".join(lines) + "\n\n"


def kiro_rules(agent: Agent) -> list[dict[str, object]]:
    rules: list[dict[str, object]] = [{"capability": "fs_read", "match": ["**/*"], "effect": "allow"}]
    if agent.writes:
        rules += [
            {"capability": "fs_write", "match": ["**/*"], "exclude": [f"{WORK_DIR}/**"], "effect": "deny"},
            {"capability": "fs_write", "match": [f"{WORK_DIR}/**"], "effect": "allow"},
        ]
    else:
        rules.append({"capability": "fs_write", "match": ["**/*"], "effect": "deny"})
    if agent.shell:
        rules += [
            {"capability": "shell", "match": ["*"], "exclude": [SHELL], "effect": "deny"},
            {"capability": "shell", "match": [SHELL], "effect": "allow"},
        ]
    else:
        rules.append({"capability": "shell", "match": ["*"], "effect": "deny"})
    if agent.web:
        rules += [{"capability": "web_fetch", "match": ["*"], "effect": "allow"}, {"capability": "web_search", "match": ["*"], "effect": "allow"}]
    else:
        rules += [{"capability": capability, "match": ["*"], "effect": "deny"} for capability in ("web_fetch", "web_search")]
    rules.append({"capability": "subagent", "match": ["*"], "effect": "deny"})
    return rules


def opencode_permissions(agent: Agent) -> list[dict[str, str]]:
    rules = [{"action": "*", "resource": "*", "effect": "deny"}]
    rules += [{"action": action, "resource": "*", "effect": "allow"} for action in ("read", "glob", "grep", "skill")]
    if agent.writes:
        rules += [{"action": "edit", "resource": "*", "effect": "deny"}, {"action": "edit", "resource": f"{WORK_DIR}/**", "effect": "allow"}]
    else:
        rules.append({"action": "edit", "resource": "*", "effect": "deny"})
    if agent.shell:
        rules += [{"action": "shell", "resource": "*", "effect": "deny"}, {"action": "shell", "resource": SHELL, "effect": "allow"}]
    else:
        rules.append({"action": "shell", "resource": "*", "effect": "deny"})
    rules.append({"action": "subagent", "resource": "*", "effect": "deny"})
    if agent.web:
        rules.extend({"action": action, "resource": "*", "effect": "allow"} for action in ("webfetch", "websearch"))
    else:
        rules.extend({"action": action, "resource": "*", "effect": "deny"} for action in ("webfetch", "websearch"))
    return rules


def toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render(agent: Agent, harness: str) -> str:
    prompt = prompt_comment(agent, harness) + agent.prompt
    if harness == "claude":
        tools = [tool for capability in agent.capabilities for tool in CLAUDE_TOOLS[capability]]
        front = "\n".join(("---", f"name: {agent.name}", f"description: {json.dumps(agent.description, ensure_ascii=False)}", f"tools: {', '.join(tools)}", f"skills: {json.dumps(list(agent.skills), ensure_ascii=False)}", "model: inherit", "---"))
        return f"{front}\n\n{prompt}\n"
    if harness == "codex":
        return "\n".join((f"name = {toml_string(agent.name)}", f"description = {toml_string(agent.description)}", f"developer_instructions = {toml_string(prompt)}", ""))
    if harness == "opencode":
        rules = [f"  - action: {json.dumps(rule['action'])}\n    resource: {json.dumps(rule['resource'], ensure_ascii=False)}\n    effect: {rule['effect']}" for rule in opencode_permissions(agent)]
        front = "\n".join(("---", f"description: {json.dumps(agent.description, ensure_ascii=False)}", "mode: subagent", "permissions:", *rules, "---"))
        return f"{front}\n\n{prompt}\n"
    if harness == "kiro":
        tools = ["read"] + (["write"] if agent.writes else []) + (["shell"] if agent.shell else []) + (["web"] if agent.web else [])
        value = {"name": agent.name, "description": agent.description, "prompt": OWNERSHIP_MARKER + "\n\n" + agent.prompt, "tools": tools, "permissions": {"rules": kiro_rules(agent)}, "resources": [f"skill://.kiro/skills/{skill}/SKILL.md" for skill in agent.skills]}
        return json.dumps(value, indent=2, ensure_ascii=False) + "\n"
    raise ValueError(f"unknown harness {harness!r}")


def output_path(name: str, harness: str) -> Path:
    extension = {"claude": "md", "codex": "toml", "opencode": "md", "kiro": "json"}[harness]
    return OUTPUTS[harness] / f"{name}.{extension}"


def opencode_command() -> str:
    return """---
description: Prototype-to-CAD flow
---

Read the `cad-flow` skill and follow its workflow. With arguments, apply it to $ARGUMENTS. Without arguments, resume the existing `hw/` design record, or ask what to design when there is none.
"""


def generated() -> dict[Path, str]:
    found = agents()
    outputs = {output_path(agent.name, harness): render(agent, harness) for harness in OUTPUTS for agent in found}
    outputs[OPENCODE_COMMAND] = opencode_command()
    return outputs


def unexpected(outputs: dict[Path, str]) -> list[Path]:
    return sorted(path for folder in (*OUTPUTS.values(), OPENCODE_COMMAND.parent) if folder.is_dir() for path in folder.iterdir() if path.is_file() and path not in outputs)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are missing, stale, or unexpected")
    args = parser.parse_args()
    try:
        outputs = generated()
    except (OSError, KeyError, ValueError) as error:
        print(f"FAIL: {error}", file=sys.stderr)
        return 1
    drift: list[str] = []
    for path, expected in outputs.items():
        if args.check:
            if not path.is_file():
                drift.append(f"missing {path.relative_to(ROOT)}")
            elif path.read_text(encoding="utf-8") != expected:
                drift.append(f"stale {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8")
            print(f"generated {path.relative_to(ROOT)}")
    for path in unexpected(outputs):
        if args.check:
            drift.append(f"unexpected {path.relative_to(ROOT)}")
        else:
            path.unlink()
            print(f"removed {path.relative_to(ROOT)}")
    if drift:
        print("FAIL: generated harness files differ from neutral agent sources:", file=sys.stderr)
        for item in drift:
            print(f"  {item}", file=sys.stderr)
        print("Run python3 harness/generate.py", file=sys.stderr)
        return 1
    if args.check:
        print(f"PASS: {len(outputs)} harness files current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())